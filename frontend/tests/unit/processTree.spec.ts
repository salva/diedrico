/**
 * Unit tests for ProcessTree
 * 
 * Tests the process tree's ability to:
 * - Track construction actions
 * - Maintain tree structure
 * - Traverse in execution order
 */

import { describe, it, expect, beforeEach } from 'vitest';
import { ProcessTree, type ActionGroup } from '@/domain/processTree/ProcessTree';
import type { Action } from '@/domain/processTree/Action';
import { createPointAction } from '@/domain/processTree/actions/CreatePointAction';
import { createLineAction } from '@/domain/processTree/actions/CreateLineAction';
import { Vector3 } from 'three';

describe('ProcessTree', () => {
  let tree: ProcessTree;

  beforeEach(() => {
    tree = new ProcessTree();
  });

  function addActionInExplicitGroup(action: Action, groupId = `group-${action.elementId}`): ActionGroup {
    const group: ActionGroup = {
      id: groupId,
      type: 'actionGroup',
      children: [],
      isAuxiliary: false,
      isOutput: true,
      created: new Date()
    };
    tree.addActionGroup(group);
    tree.addActionToGroup(action, group.id);
    return group;
  }

  describe('initialization', () => {
    it('should create a root subprocess', () => {
      expect(tree.root).toBeDefined();
      expect(tree.root.type).toBe('subprocess');
      expect(tree.root.name).toBe('Root Process');
      expect(tree.root.children).toEqual([]);
    });
  });

  describe('explicit action-group insertion', () => {
    it('assigns deterministic action node IDs', () => {
      const action1 = createPointAction('point_1');
      const action2 = createPointAction('point_2');

      const group1 = addActionInExplicitGroup(action1);
      const group2 = addActionInExplicitGroup(action2);

      expect(group1.children[0]?.id).toBe('node1');
      expect(group2.children[0]?.id).toBe('node2');
    });

    it('should add a point action to an explicit group', () => {
      const action = createPointAction('point_1');
      const group = addActionInExplicitGroup(action);

      expect(group.type).toBe('actionGroup');
      expect(group.children).toHaveLength(1);
      // Phase 93: Actions don't have id, ActionNode does (generated by ProcessTree)
      expect(group.children[0].elementId).toBe(action.elementId);
      expect(tree.root.children).toContain(group);
    });

    it('should add a line action to an explicit group', () => {
      const action = createLineAction('line_1');
      const group = addActionInExplicitGroup(action);

      expect(group.type).toBe('actionGroup');
      expect(group.children).toHaveLength(1);
      // Phase 93: Actions don't have id, ActionNode does (generated by ProcessTree)
      expect(group.children[0].elementId).toBe(action.elementId);
    });

    it('should preserve caller-created separate action groups', () => {
      const action1 = createPointAction('point_1');
      const action2 = createPointAction('point_2');

      addActionInExplicitGroup(action1);
      addActionInExplicitGroup(action2);

      expect(tree.root.children).toHaveLength(2);
    });
  });

  describe('addSubprocess', () => {
    it('reserves explicit subprocess IDs before generating later node IDs', () => {
      tree.pushSubprocess('Loaded subprocess', 'node7');
      tree.popSubprocess();

      const subprocess = tree.addSubprocess('Later subprocess');

      expect(subprocess.id).toBe('node8');
    });

    it('should add a subprocess to the root', () => {
      const subprocess = tree.addSubprocess('Construction Phase 1');

      expect(subprocess.type).toBe('subprocess');
      expect(subprocess.name).toBe('Construction Phase 1');
      expect(subprocess.showIntermediates).toBe(true);
      expect(subprocess.isOutput).toBe(true);
      expect(tree.root.children).toContain(subprocess);
    });

    it('should add a nested subprocess', () => {
      const parent = tree.addSubprocess('Phase 1');
      const child = tree.addSubprocess('Substep A', parent);

      expect(parent.children).toContain(child);
      expect(child.type).toBe('subprocess');
    });
  });

  describe('getAllActions', () => {
    it('should return empty array for empty tree', () => {
      const actions = tree.getAllActions();
      expect(actions).toEqual([]);
    });

    it('should return all actions in execution order', () => {
      const action1 = createPointAction('point_1');
      const action2 = createPointAction('point_2');
      const action3 = createLineAction('line_1');

      addActionInExplicitGroup(action1);
      addActionInExplicitGroup(action2);
      addActionInExplicitGroup(action3);

      const actions = tree.getAllActions();
      expect(actions.length).toBe(3);
      // Phase 93: Actions don't have id property, ActionNodes do. Verify by elementId instead.
      expect(actions[0].elementId).toBe(action1.elementId);
      expect(actions[1].elementId).toBe(action2.elementId);
      expect(actions[2].elementId).toBe(action3.elementId);
    });

    it('should traverse nested subprocesses in depth-first order', () => {
      const subprocess = tree.addSubprocess('Phase 1');
      const action1 = createPointAction('point_1');
      const action2 = createPointAction('point_2');

      // Add action to root first
      addActionInExplicitGroup(action1);

      // Manually add action to subprocess for testing
      const group = {
        id: 'group_test',
        type: 'actionGroup' as const,
        name: 'Test Group',
        children: [action2],
        isAuxiliary: false,
        created: new Date()
      };
      subprocess.children.push(group);

      const actions = tree.getAllActions();
      // Depth-first traversal visits children in order: first action group (action1), then subprocess (action2)
      expect(actions).toHaveLength(2);
      // Phase 93: Compare by elementId, not id (Actions don't have id)
      expect(actions[0].elementId).toBe(action2.elementId); // Subprocess comes first in children
      expect(actions[1].elementId).toBe(action1.elementId); // Root action group comes after
    });
  });

  describe('findAction', () => {
    it('should find action by ID (ActionNode ID)', () => {
      const action = createPointAction('point_1');
      const group = addActionInExplicitGroup(action);
      const actionNode = group.children[0];

      // Phase 93: findAction uses ActionNode id (not Action id)
      const found = tree.findAction(actionNode.id);
      expect(found?.id).toBe(actionNode.id);
      expect(found?.elementId).toBe('point_1');
    });

    it('should return undefined for non-existent action', () => {
      const found = tree.findAction('non_existent');
      expect(found).toBeUndefined();
    });
  });

  describe('getActionsProducingElement', () => {
    it('should find actions that produce a specific element', () => {
      const action1 = createPointAction('point_1');
      const action2 = createPointAction('point_2');
      const action3 = createLineAction('line_1');

      addActionInExplicitGroup(action1);
      addActionInExplicitGroup(action2);
      addActionInExplicitGroup(action3);

      const producers = tree.getActionsProducingElement('point_1');
      expect(producers).toHaveLength(1);
      expect(producers[0].elementId).toBe(action1.elementId);
    });

    it('should return empty array if no action produces the element', () => {
      const action = createPointAction('point_1');
      addActionInExplicitGroup(action);

      const producers = tree.getActionsProducingElement('point_99');
      expect(producers).toEqual([]);
    });
  });

  describe('action factory functions', () => {
    it('createPointAction should create valid action with elementId', () => {
      const action = createPointAction('point_1');

      // Phase 93: Actions only have 3 fields (elementId, description, isOutput)
      expect(action.elementId).toBe('point_1');
      expect(action.description).toContain('point_1');
      expect(action.isOutput).toBe(true); // Phase 93: defaults to true
    });

    it('createLineAction should create valid action with elementId', () => {
      const action = createLineAction('line_1');

      // Phase 93: Actions only have 3 fields (elementId, description, isOutput)
      expect(action.elementId).toBe('line_1');
      expect(action.description).toContain('line_1');
      expect(action.isOutput).toBe(true); // Phase 93: defaults to true
    });
  });
});
