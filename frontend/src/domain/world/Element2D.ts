import type { ProjectionElementRealizationContext } from './projectionPlane/ProjectionPlaneContext';
import { Point2DRealization2D } from './Point';
import { Line2DRealization2D } from './Line';
import { Circle2DRealization2D } from './Circle';
import { validateElementId } from './ElementId';
import { Element } from './Element';

/**
 * Union type for all possible 2D element realizations
 */
export type Element2DRealization = Point2DRealization2D | Line2DRealization2D | Circle2DRealization2D;

/**
 * Base class for all 2D geometric elements.
 *
 * Element IDs must be hierarchical and scoped to their containing projection
 * plane. Runtime dispatch uses concrete classes with instanceof; do not add
 * broad kind/type fields unless a serialization boundary requires them.
 *
 * @sealed - Only Point2D, Line2D, and Circle2D extend it.
 */
export abstract class Element2D extends Element {
  /** Which projection plane this element belongs to */
  readonly planeId: string;
  
  /**
   * Construct a 2D element
   * 
   * @param id Element ID in hierarchical format: '{planeId}/{localId}' (e.g., 'proj_plane_1/point2d_5')
   *           This ID must be generated by the containing plane's factory methods or ID generators.
   *           NEVER pass hardcoded non-hierarchical IDs like 'p1' or 'point2d_5' - they will fail validation.
   * @param planeId ID of the projection plane that contains this element
   * @param label Optional user-friendly label for UI display
   */
  constructor(
    id: string,
    planeId: string,
    label?: string
  ) {
    super(id, label);
    
    validateElementId(id, planeId);
    
    this.planeId = planeId;
  }
  
  /**
   * Clone this element
   * Must be implemented by concrete subclasses
   */
  abstract clone(): Element2D;
  
  /**
   * Calculate 2D realization (geometric position/shape) for this element
   * Returns realization in the projection plane's intrinsic coordinates
   * 
   * @param world World instance to query parent element realizations
   * @returns Element realization. Geometric failures are represented by an infeasible realization.
   */
  abstract realize2D(context: ProjectionElementRealizationContext): Element2DRealization;
}
